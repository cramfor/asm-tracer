/* Apply styling to the cells that might hold arrows to shrink them
 * a little.  Default sizing was wasting lots of space here. */
const arrowTDStyle = "width: 24px;";

/* Apply styling to the arrow figures to remove margins to shrink them
 * a little.  Default sizing was wasting lots of space here. */
const arrowStyle = "margin: 0;";

/* 只在指定容器内滚动到目标元素，避免 element.scrollIntoView() 连带滚动
 * 整个页面（scrollIntoView 会滚动所有可滚动祖先），造成页面被来回拖拽。 */
function scrollInContainer(containerId, el) {
    const c = document.getElementById(containerId);
    if (!c || !el) return;
    const delta = el.getBoundingClientRect().top - c.getBoundingClientRect().top;
    c.scrollTop += delta - c.clientHeight / 2;
}

function buildInstructionTable() {
    /* The code lives outside individual instruction data in the trace file
     * in a separate section named 'code'. */

    /* Begin generating table HTML for the instructions. */
    let html = `
    <table class="table is-hoverable is-fullwidth table-borderless is-striped">
      <thead class="is-borderless">
        <tr class="is-borderless">
          <th style="${arrowTDStyle}" class="is-borderless" ></th> <!-- intentionally blank header -- column to display arrows -->
          <th>Line</th>
          <th>Address</th>
          <th>Instruction</th>
        </tr>
      </thead>
      <tbody style="border:black;">
    `;

    let l=1;
    for (let line in trace["code"]) {
        const [addr, code] = trace["code"][line];

        //hide autogenerated lines
        if(has_offset && l<first_line) {
            l++;
            continue;
        }
        else if(has_offset && l>last_line) {
            break;
        }

        /* Keep track of which instructions have addresses associated with
         * them so that we can update arrows in the table.  If the address
         * is bogus (0x0), don't display it. */
        if (addr != "0x0") {
                codeAddressSet.add(addr);
                html += `
                <tr class="is-borderless">
                  <td  id="instr_${addr}" style="${arrowTDStyle}"></td>
                  <td style="border:black">${line}</td>
                  <td >${addr}</td>
                  <td>${code.replace(/\\t/g, "&nbsp;&nbsp;&nbsp;&nbsp;")}</td>
                </tr>
                `;
        }

        else {
                // Address field intentionally blank.
                html += `
                <tr>
                  <td  id="instr_${addr}" style="${arrowTDStyle}"></td>
                  <td>${line}</td>
                  <td></td>
                  <td>${code.replace(/\\t/g, "&nbsp;&nbsp;&nbsp;&nbsp;")}</td>
                </tr>
                `;
        }
        l++;
    }

    /* Close out the table HTML. */
    html += `
      </tbody>
    </table>
    `;

    /* Replace the 'loading' placeholder with this new table HTML. */
    document.getElementById("instruction_content").innerHTML = html;
    return;
}

/* outstandingStackAddrs: a Set() containing all the stack addresses that will
 * appear on the stack in the current instruction.  Used to construct the
 * "Stack Content" table in the middle of the page. */
function buildStackTable(outstandingStackAddrs) {

    /* Convert the set of unique addresses into a sorted array.  We need these
     * addresses in sorted order so that the stack correctly shows memory
     * contiguously. */
    let stackAddresses = Array.from(outstandingStackAddrs).sort();

    /* Begin generating table HTML for the stack. */
    let html = `
    <table class="table is-borderless is-hoverable is-fullwidth is-striped">
      <thead>
        <tr>
          <th style="${arrowTDStyle}"></th> <!-- intentionally blank header -- column to display arrows -->
          <th>Address</th>
          <th>Value</th>
        </tr>
      </thead>
      <tbody>
    `;

    /* For each addresses, add the address and a location for the value, where
     * the value's cell has a unique ID of stack_ADDR so that we can reference
     * it later when we need to update the cell. */

    for (let addr of stackAddresses) {
        html += `
        <tr id="stack_row_${addr}" class="">
          <td id="stack_arrow_${addr}" style="${arrowTDStyle}"></td>
          <!--<td>${addr}</td>-->
          <td id="stack_address_${addr}">${addr}</td>
          <td id="stack_${addr}"></td>
        </tr>
        `;
    }

    /* Close out the table HTML. */
    html += `
      </tbody>
    </table>
    `;

    /* Replace the 'loading' placeholder with this new table HTML. */
    document.getElementById("stack_content").innerHTML = html;
    return;
}

function buildRegisterTable() {
    /* We only want to display registers that actually get used during the
     * execution of the code we're tracing.  This dictionary keeps track of
     * the registers that we do want to display (true) vs. those we don't
     * (false).  Initially, they're all false.  We change a register to true
     * if either:
     * 1) the register's name appears in an instruction, or
     * 2) the register's value changes throughout execution. */

    for (let reg in trace["instructions"]["1"]["registers"]) {
        registerStatus[reg] = false;
    }

    //ALWAYS DISPLAY CONDITION CODE REGISTER
    let condReg=getFlags();
    registerStatus[condReg]=true;
    let [stackReg,bottomReg]=getStackRegisters();
    registerStatus[stackReg]=true;
    registerStatus[bottomReg]=true;

    /* Check instructions. */
    for (let line in trace["code"]) {
        const [addr, code] = trace["code"][line];

        for (let reg in registerStatus) {
            if (code.toLowerCase().includes(reg.toLowerCase())) {
                registerStatus[reg] = true;
            }
        }
    }

    /* Check register values changing. */
    for (let i in trace["instructions"]) {
        for (let reg in registerStatus) {
            if (trace["instructions"]["1"]["registers"][reg] !== trace["instructions"][i]["registers"][reg]) {
                registerStatus[reg] = true;
            }
        }
    }

    /* Begin generating table HTML for the registers. */
    let html = `
    <table class="table is-borderless is-hoverable is-fullwidth is-striped">
      <thead>
        <tr>
          <th>Register</th>
          <th>Value</th>
        </tr>
      </thead>
      <tbody>
    `;

    /* For each register that changed or appeared in an instruction, add a
     * row in the resulting table. */
    for (let reg in registerStatus) {
        if (registerStatus[reg]) {
            html += `
            <tr id="reg_row${reg}">
              <td id="reg_row_addr${reg}">${reg}</td>
              <td id="reg_${reg}"></td>
            </tr>
            `;
        }
    }

    /* Close out the table HTML. */
    html += `
      </tbody>
    </table>
    `;

    /* Replace the 'loading' placeholder with this new table HTML. */
    document.getElementById("register_content").innerHTML = html;
    return;
}

function getFlags() {
    /* System arch will be one of:
     * arm64  x86-64  IA32  */

    if (trace["system"]["arch"] == "arm64") {
        return ["NZCV"];
    }

    if (trace["system"]["arch"] == "x86-64") {
        return ["RFLAG"];
    }

    if (trace["system"]["arch"] == "IA32") {
        return ["EFLAG"];
    }

    /* If we made it here, something is very wrong. */
    console.log(`Unknown architecture: ${trace["system"]["arch"]}`);

    return [null];
}

function getStackRegisters() {
    /* System arch will be one of:
     * arm64  x86-64  IA32  */

    if (trace["system"]["arch"] == "arm64") {
        return ["SP", "X29(FP)"];
    }

    if (trace["system"]["arch"] == "x86-64") {
        return ["RSP", "RBP"];
    }

    if (trace["system"]["arch"] == "IA32") {
        return ["ESP", "EBP"];
    }

    /* If we made it here, something is very wrong. */
    console.log(`Unknown architecture: ${trace["system"]["arch"]}`);

    return [null, null];
}

