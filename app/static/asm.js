//toggle between expanded & condensed arithmetic mode
function setOffset(){
    has_offset=!has_offset;

    //condense view
    if(has_offset) {
        frontend_max = saved_max;

        if(backend_step < first_instruction) {
            backend_step = first_instruction - 1;
            frontend_step = 0;
        }

        else if (backend_step > last_instruction) {
            backend_step = last_instruction;
            frontend_step = last_instruction;
        }

        else {
            frontend_step = backend_step - 1;
        }

    }

    //expand view
    else {
        frontend_step = backend_step;
        frontend_max = backend_max;
    }

    setCurrentStep(backend_step);
    return;
}

//step box
function jumpToStep() {
    jump_to = Number(document.getElementById("jump_to_step").value)
    if((jump_to >= 1) && (jump_to <= frontend_max)) {
        if(has_offset) {
            setCurrentStep(jump_to + first_instruction);
        } else {
            setCurrentStep(jump_to);
        }
        return;
    }
}

