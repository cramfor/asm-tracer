//update output
function setCurrentOutput() {
    /* Instead of the above, start from the current instruction and look
     * backwards for the most recent instruction with output, if there is one. */
    for (let i = backend_step; i >= 0; i--) {
        if (`${i}` in trace["instructions"] && "stdout" in trace["instructions"][`${i}`]) {
            let outputLine = trace["instructions"][`${i}`]["stdout"].replace(/\\n/g, "<br>");

            document.getElementById("outputDiv").style.display="block";
            document.getElementById("output").innerHTML = "";
            document.getElementById("output").innerHTML = `${outputLine}`;
            break;
        }

        else {
            document.getElementById("outputDiv").style.display="none";
        }
    }

    if ("final_output" in trace && backend_step == maxStep) {
        /* If we're in the fake step with extra output at the end... */
        let outputLine = trace["final_output"].replace(/\\n/g, "<br>");

        document.getElementById("output").innerHTML = "";
        document.getElementById("output").innerHTML = `${outputLine}`;
        document.getElementById("output").innerHTML += `${outputLine}`;
    }
    return;
}

//display JSON content for trace['instructions']['snum']
function setCurrentStep(snum) {
    console.log(`Set current step to: ${snum}`);
    backend_step = snum;

    //fast-forward to first condensed instruction
    if(has_offset & (backend_step < first_instruction)) {
        backend_step = first_instruction;
        console.log(`Set current step to: ${backend_step}`);
        frontend_step = 0;
    }

    //update display step for condensed view
    else if(has_offset) {
        frontend_step = backend_step - first_instruction;
    }

    //update display step for expanded view or function/full program mode
    else {
        frontend_step = backend_step;
    }

    /* Set current step number display above buttons. */
    document.getElementById("step_text").innerHTML = ` of ${frontend_max}`;
    document.getElementById("jump_to_step").value = `${frontend_step}`;

    //hide conditional displays
    document.getElementById("errorDiv").style.display="none";
    document.getElementById("outputDiv").style.display="none";
    if (any_instructions) {
        document.getElementById("warningDiv").style.display="none";
    }

    //populate instruction table
    buildInstructionTable();

    /* Set local variables to represent the current and previous step
     * dictionaries from the trace.  This aliasing is for convenience.  Note:
     * one or both might be remain null if there is no such step (e.g., step
     * 0). */

    let currentInstruction = null;
    let prevInstruction = null;

    //find current instruction
    if (`${backend_step}` in trace["instructions"]) {
        currentInstruction = trace["instructions"][`${backend_step}`];
    }

    //find previous instruction
    if (`${backend_step - 1}` in trace["instructions"]) {
        prevInstruction = trace["instructions"][`${backend_step - 1}`];
    }

    try {
        /* Set green/red arrows in front of instructions based on IP values. */
        setCurrentCodeArrows(currentInstruction, prevInstruction);

        /* Set stack values for the current instruction. */
        setCurrentStack(currentInstruction, prevInstruction);

        /* Set register values for the current instruction. */
        setCurrentRegisters(currentInstruction, prevInstruction);

        /* Set the output by looking backwards though instructions. */
        setCurrentOutput(backend_step, currentInstruction, prevInstruction);

    }
    catch (e) {
        console.log("Error:");
        console.log(e.name);
        console.log(e.message);
        console.log(e.stack);
        setError();
    }

    /* Set error content on last step */
    //if ((backend_step == backend_max) || (frontend_step == frontend_max)) {
    //    setError();
    //}
    return;
}

